/** ADJECTIVE + PLACE, FOR EXAMPLE AMBER CAY */
export function randomArchipelagoName(rng: () => number = Math.random): string {
  const adjective = ADJECTIVES[Math.floor(rng() * ADJECTIVES.length)]!;
  const place = PLACES[Math.floor(rng() * PLACES.length)]!;
  return `${adjective} ${place}`;
}
